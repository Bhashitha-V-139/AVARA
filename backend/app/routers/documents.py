import re
from pathlib import Path

from fastapi import APIRouter, File, HTTPException, UploadFile

from app.config import settings
from app.database import get_document, insert_document, list_documents
from app.schemas import DocumentInfo, DocumentPages, PageText, UploadResponse
from app.services.document_manager import delete_document
from app.services.extraction import extract_pages
from app.services.indexing import index_document
from app.services.storage import save_pdf_upload, validate_pdf_upload
from app.services.vector_store import delete_document_chunks

router = APIRouter(prefix="/documents", tags=["documents"])

# Document IDs are 32-character lowercase hex strings generated by uuid4().hex
DOCUMENT_ID_PATTERN = re.compile(r"^[0-9a-f]{32}$")


def _check_document_id(document_id: str) -> None:
    if not DOCUMENT_ID_PATTERN.match(document_id):
        raise HTTPException(status_code=400, detail="Invalid document ID.")


@router.post("/upload", response_model=UploadResponse, status_code=201)
def upload_document(file: UploadFile = File(...)) -> UploadResponse:
    """Upload a PDF, extract and index its pages, and record it in the database."""
    validate_pdf_upload(file)
    document_id, path, size, uploaded_at = save_pdf_upload(file)

    # Keep only the file name, never any folder part sent by the client.
    safe_filename = Path(file.filename).name

    try:
        pages = extract_pages(path)
        has_text = any(page["text"] for page in pages)
        chunk_count = index_document(document_id, safe_filename, pages) if has_text else 0
    except Exception:
        # Something failed, so remove the file and any partial vectors.
        path.unlink(missing_ok=True)
        delete_document_chunks(document_id)
        raise

    page_count = len(pages)
    status = "indexed" if has_text else "no_text"

    insert_document(
        document_id=document_id,
        filename=safe_filename,
        size_bytes=size,
        page_count=page_count,
        status=status,
        uploaded_at=uploaded_at,
    )

    message = (
        f"Document uploaded and indexed into {chunk_count} searchable chunks."
        if has_text
        else "Document uploaded, but no text was found. It may be a scanned PDF."
    )

    return UploadResponse(
        message=message,
        document=DocumentInfo(
            document_id=document_id,
            filename=safe_filename,
            size_bytes=size,
            page_count=page_count,
            status=status,
            uploaded_at=uploaded_at,
        ),
    )


@router.get("", response_model=list[DocumentInfo])
def get_documents() -> list[DocumentInfo]:
    """List all uploaded documents, newest first."""
    return [DocumentInfo(**row) for row in list_documents()]


@router.get("/{document_id}/pages", response_model=DocumentPages)
def get_document_pages(document_id: str) -> DocumentPages:
    """Return the extracted text of each page, with page numbers."""
    _check_document_id(document_id)

    record = get_document(document_id)
    if record is None:
        raise HTTPException(status_code=404, detail="Document not found.")

    path = settings.upload_dir / f"{document_id}.pdf"
    if not path.exists():
        raise HTTPException(status_code=404, detail="The stored file is missing.")

    pages = extract_pages(path)
    return DocumentPages(
        document_id=document_id,
        filename=record["filename"],
        page_count=len(pages),
        pages=[PageText(**page) for page in pages],
    )


@router.delete("/{document_id}")
def remove_document(document_id: str) -> dict:
    """Delete a document's vectors, PDF file, and database record."""
    _check_document_id(document_id)

    if not delete_document(document_id):
        raise HTTPException(status_code=404, detail="Document not found.")

    return {"message": "Document deleted.", "document_id": document_id}